/// Basename is a widget builder, or the generic `Object` fallback.
///
/// The generic `glib::Object::builder()` constructs any widget class, so it
/// counts alongside the generated per-type builders.
///
/// # Arguments
///
/// * `name` - Type basename immediately before `::builder`.
///
/// # Returns
///
/// * `bool` - True for inventoried widget builders and `Object`.
#[must_use]
pub fn is_widget_builder(name: &str) -> bool {
    name == "Object" || WIDGET_BUILDERS.contains(&name)
}

#[cfg(test)]
mod tests {
    use crate::rules_ui::missing_labels::widget_builders::{WIDGET_BUILDERS, is_widget_builder};

    #[test]
    fn widgets_count_as_builders() {
        for name in ["Button", "Label", "ActionRow", "ToastOverlay", "WebView"] {
            assert!(is_widget_builder(name), "{name} counts");
        }
        assert!(
            WIDGET_BUILDERS.len() > 150,
            "inventory covers the full widget set"
        );
    }

    #[test]
    fn non_widgets_stay_silent() {
        for name in ["Signal", "Settings", "Client", "Action", "Toast", "Builder"] {
            assert!(!is_widget_builder(name), "{name} stays silent");
        }
        assert!(is_widget_builder("Object"), "generic fallback counts");
    }
}
